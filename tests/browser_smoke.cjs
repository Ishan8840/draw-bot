// Optional end-to-end test. Requires Playwright and a running empty test server.
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const browser = await chromium.launch({headless:process.env.HEADLESS !== '0', slowMo:Number(process.env.SLOW_MO || 0), ...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {}), args:['--no-sandbox']});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1100}});
    const errors=[];
    page.on('pageerror', e => errors.push(e.message));
    const base=process.env.ASTRA_URL || 'http://127.0.0.1:8000';
    const post=async (path, body={}) => { const res=await page.request.post(base+path,{data:body}); assert.equal(res.status(),200); return res.json(); };
    const scene=async () => (await page.request.get(base+'/scene')).json();
    const waitScene=async predicate => { for(let i=0;i<200;i++){const s=await scene(); if(predicate(s))return s; await page.waitForTimeout(25);} throw Error('Timed out waiting for scene'); };
    await page.goto(base);
    await page.locator('.command-panel').evaluate(details => { details.open=true; });
    await page.waitForFunction(() => document.getElementById('connection').textContent.includes('Live'));
    await post('/commands/clear');
    await page.waitForFunction(() => document.querySelectorAll('#ink polyline').length===0);
    await page.waitForFunction(() => document.getElementById('command').value.includes('house'));
    await page.click('#execute');
    await waitScene(s => s.objects[0]?.strokes[0]?.progress > .08);
    await page.click('[data-action="pause"]');
    const paused=await waitScene(s => s.status==='paused');
    await page.waitForTimeout(80);
    assert.deepEqual(await scene(),paused);
    await page.click('[data-action="resume"]');
    await waitScene(s => s.objects[0].strokes[0].progress>paused.objects[0].strokes[0].progress);
    await page.click('[data-action="cancel"]');
    const cancelled=await waitScene(s => s.status==='cancelled');
    const before=cancelled.objects[0];
    assert(before.strokes[0].executed_points.length>=2);
    assert(before.strokes[0].progress<1);
    await post('/commands/speed',{speed:5});
    await page.selectOption('#example','x');
    await page.waitForFunction(() => JSON.parse(document.getElementById('command').value).object_id.startsWith('x-'));
    await page.click('#execute');
    const done=await waitScene(s => s.status==='idle' && s.objects.length===2);
    assert.deepEqual(done.objects[0],before);
    const expected=done.objects.flatMap(o=>o.strokes).map(s=>s.executed_points.map(p=>`${p.x*1000},${p.y*1000}`).join(' '));
    await page.reload();
    await page.locator('.command-panel').evaluate(details => { details.open=true; });
    await page.waitForFunction(() => document.querySelectorAll('#ink polyline').length===7);
    assert.deepEqual(await page.locator('#ink polyline').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('points'))),expected);
    await page.check('#pen');
    const box=await page.locator('#board').boundingBox();
    await page.mouse.move(box.x+box.width*.1,box.y+box.height*.85);
    await page.mouse.down();
    await page.mouse.move(box.x+box.width*.25,box.y+box.height*.9,{steps:12});
    await page.mouse.move(box.x+box.width*.4,box.y+box.height*.85,{steps:12});
    await page.mouse.up();
    const manual=await waitScene(s=>s.objects.some(o=>o.source==='user'));
    const mark=manual.objects.at(-1).strokes[0];
    assert.equal(mark.progress,1);
    assert(mark.executed_points.length>10);
    await page.selectOption('#example','circle');
    await page.waitForFunction(() => JSON.parse(document.getElementById('command').value).object_id.startsWith('circle-'));
    await page.click('#execute');
    await waitScene(s=>s.status==='idle' && s.objects.length===4);
    const circle=page.locator('#ink polyline').last();
    await page.waitForFunction(() => document.querySelectorAll('#ink polyline').length===9);
    const bounds=await circle.evaluate(node=>{const b=node.getBBox();return {x:b.x,y:b.y,width:b.width,height:b.height};});
    assert(Math.abs(bounds.width-600)<.01 && Math.abs(bounds.height-600)<.01);
    await page.screenshot({path:process.env.ASTRA_SCREENSHOT || '/tmp/astra-desktop.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    const mobileBoard=await page.locator('#board').boundingBox();
    assert(Math.abs(mobileBoard.width-mobileBoard.height)<1);
    await page.screenshot({path:'/tmp/astra-mobile.png',fullPage:true});
    assert.deepEqual(errors,[]);
    console.log('Browser checks passed: interrupt/resume/cancel, new drawing, reload reconstruction, manual input, circle bounds, mobile layout, no JS errors.');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
